"""Coral health report builder (Markdown; the PDF layer adds print formatting)."""

from __future__ import annotations

from pathlib import Path
from typing import Mapping, Sequence

from ..utils import ensure_dir
from .risk import RiskProfile
from .severity import SeverityAssessment, SEVERITY_CLASSES


def _bar(percent: float, width: int = 24) -> str:
    filled = int(round(width * float(np_clip(percent)) / 100)) if False else int(round(width * min(max(percent, 0), 100) / 100))
    return "[" + "#" * filled + "-" * (width - filled) + "]"


def np_clip(x: float) -> float:  # tiny local helper (avoids numpy import noise)
    return max(0.0, min(100.0, float(x)))


def build_health_report_markdown(
    out_path: str | Path,
    site_name: str,
    assessments: Sequence[SeverityAssessment],
    risk: RiskProfile | None = None,
    summary: Mapping | None = None,
    trend_lines: Sequence[str] | None = None,
    biodiversity_note: str | None = None,
) -> Path:
    """Write a human-readable coral health report and return its path."""
    if not assessments:
        raise ValueError("No coral assessments supplied for the report.")

    agg = summary or _aggregate(assessments)
    dist = agg.get("distribution", {})
    lines: list[str] = []
    lines.append(f"# Coral Reef Health Report — {site_name}")
    lines.append("")
    lines.append("> Generated by **ReefScan AI** — Whiteness-Guided Bleaching Severity (WGBS) pipeline.")
    lines.append("")
    lines.append("## Executive summary")
    lines.append("")
    lines.append(f"- **Mean bleaching severity index (BSI):** {agg['mean_index']:.1f} / 100 {_bar(agg['mean_index'])}")
    lines.append(f"- **Dominant condition:** {str(agg.get('dominant_class', 'n/a')).capitalize()}")
    lines.append(f"- **Patches analysed:** {agg.get('n_patches', len(assessments))}")
    if risk is not None:
        lines.append(f"- **Environmental risk:** {risk.category} ({risk.score:.0f}/100) — {', '.join(risk.drivers)}")
    lines.append("")

    lines.append("## Condition distribution")
    lines.append("")
    lines.append("| Condition | Share |")
    lines.append("|---|---|")
    for cls in SEVERITY_CLASSES:
        lines.append(f"| {cls.capitalize()} | {100 * dist.get(cls, 0.0):.1f}% |")
    lines.append("")

    lines.append("## Per-patch assessments")
    lines.append("")
    lines.append("| # | BSI | Condition | P(bleached) | Whiteness |")
    lines.append("|---|---|---|---|---|")
    for i, a in enumerate(assessments, 1):
        lines.append(f"| {i} | {a.index:.1f} | {a.label} | {a.p_bleached:.2f} | {a.whiteness:.2f} |")
    lines.append("")

    if trend_lines:
        lines.append("## Trend observations")
        lines.append("")
        lines.extend(f"- {t}" for t in trend_lines)
        lines.append("")

    if biodiversity_note:
        lines.append("## Biodiversity context")
        lines.append("")
        lines.append(biodiversity_note)
        lines.append("")

    if risk is not None:
        lines.append("## Recommendations")
        lines.append("")
        lines.extend(f"- {a}" for a in risk.actions)
        lines.append("")

    lines.append("---")
    lines.append("*Severity classes: Healthy [0-15) · Mild [15-35) · Moderate [35-60) · Severe [60-85) · Dead [85-100].*")

    out_path = ensure_dir(Path(out_path).parent) / Path(out_path).name
    out_path.write_text("\n".join(lines), encoding="utf-8")
    return out_path


def _aggregate(assessments: Sequence[SeverityAssessment]) -> dict:
    indices = [a.index for a in assessments]
    classes = [a.class_name for a in assessments]
    dist = {c: classes.count(c) / len(classes) for c in SEVERITY_CLASSES}
    dominant = max(dist, key=lambda k: dist[k])
    return {
        "mean_index": sum(indices) / len(indices),
        "dominant_class": dominant,
        "distribution": dist,
        "n_patches": len(assessments),
    }
