#!/usr/bin/env python
"""Compare all runs and write the final selection into the ledger.

Aggregates ``runs/**/manifest.json`` + ``results/<task>/<model>/metrics.json``
into ``results/comparison/final_comparison.csv`` (and a Markdown twin), then
writes the "Final selection" section of ``my_requested_thing.md``: for each
task, the winning model per strategy family, with the overall winner and the
tie-breaking rationale (metric first, then fewer params, then higher fps).

Usage:
    python scripts/compare_runs.py [--metric weighted_f1]
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

ROOT = Path(__file__).resolve().parents[1]
RUNS_DIR = ROOT / "runs"
RESULTS_DIR = ROOT / "results"
LEDGER = ROOT / "my_requested_thing.md"
SELECTION_START = "<!-- FINAL-SELECTION:START -->"
SELECTION_END = "<!-- FINAL-SELECTION:END -->"

TASK_METRICS = {"fish": "weighted_f1", "coral": "weighted_f1", "seg": "dice"}


def collect_rows() -> list[dict]:
    rows = []
    for manifest_path in sorted(RUNS_DIR.rglob("manifest.json")):
        with open(manifest_path, "r", encoding="utf-8") as fh:
            m = json.load(fh)
        task = m.get("task")
        metrics = m.get("final_metrics", {})
        params = m.get("params", {})
        rows.append({
            "task": task,
            "model": m.get("model"),
            "strategy": m.get("strategy"),
            "platform": m.get("platform"),
            "dataset": m.get("dataset"),
            "params_m": round(params.get("params_total", 0) / 1e6, 2),
            "train_minutes": round(m.get("train_seconds", 0) / 60, 1),
            "git_sha": m.get("git_sha"),
            "manifest": str(manifest_path.relative_to(ROOT)),
            "accuracy": metrics.get("accuracy"),
            "macro_ap": metrics.get("macro_ap"),
            "macro_f1": metrics.get("macro_f1"),
            "weighted_f1": metrics.get("weighted_f1"),
            "iou": metrics.get("iou"),
            "dice": metrics.get("dice"),
            "box_ap50": metrics.get("box_ap50"),
            "pixel_ap": metrics.get("pixel_ap"),
        })
    return rows


def pick_winners(df: pd.DataFrame, metric_by_task: dict[str, str]) -> list[dict]:
    winners = []
    for task, group in df.groupby("task"):
        metric = metric_by_task.get(task, "weighted_f1")
        group = group.copy()
        # metric desc -> fewer params asc -> not used for seg (dice/iou similar)
        group = group.sort_values(by=[metric, "params_m"], ascending=[False, True])
        best = group.iloc[0].to_dict()
        best["_metric"] = metric
        best["_best_fe"] = ""
        fe = group[group["strategy"] == "feature_extraction"]
        if not fe.empty:
            best["_best_fe"] = str(fe.sort_values(metric, ascending=False).iloc[0]["model"])
        winners.append(best)
    return winners


def render_selection(winners: list[dict]) -> str:
    lines = [
        SELECTION_START,
        "",
        "### Final selection (auto-generated by scripts/compare_runs.py)",
        "",
    ]
    for w in winners:
        metric = w["_metric"]
        value = w.get(metric)
        value_s = f"{value:.4f}" if isinstance(value, float) else "—"
        lines += [
            f"**{w['task']}** → `{w['model']}` ({w['strategy']}, trained on {w['platform']}) — "
            f"best {metric} = **{value_s}**, {w['params_m']}M params, {w['train_minutes']} min training. "
            f"Best feature-extraction screen: `{w['_best_fe'] or '—'}`.",
            "",
        ]
    lines += [
        "_Rationale: highest task metric wins; ties broken by fewer parameters "
        "(cheaper inference for the real-time pipeline) then training cost. "
        "Run `python scripts/compare_runs.py` after all platform runs to refresh._",
        "",
        SELECTION_END,
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--metric", default=None, help="Override ranking metric for all tasks")
    args = parser.parse_args()

    rows = collect_rows()
    if not rows:
        print("No manifests under runs/ — nothing to compare yet.")
        return 0
    df = pd.DataFrame(rows)

    out_dir = RESULTS_DIR / "comparison"
    out_dir.mkdir(parents=True, exist_ok=True)
    df.to_csv(out_dir / "final_comparison.csv", index=False)

    metric_by_task = dict(TASK_METRICS)
    if args.metric:
        metric_by_task = {t: args.metric for t in metric_by_task}
    winners = pick_winners(df, metric_by_task)

    md_table = df.sort_values(["task", "weighted_f1"], ascending=[True, False]).to_markdown(index=False)
    (out_dir / "final_comparison.md").write_text(
        "# ReefScan AI — final cross-platform comparison\n\n" + md_table + "\n",
        encoding="utf-8",
    )

    # Update ledger selection section.
    if LEDGER.exists():
        text = LEDGER.read_text(encoding="utf-8")
        block = render_selection(winners)
        if SELECTION_START in text and SELECTION_END in text:
            pre = text[: text.index(SELECTION_START)]
            post = text[text.index(SELECTION_END) + len(SELECTION_END):]
            text = pre + block + post
        else:
            text = text.rstrip() + "\n\n" + block + "\n"
        LEDGER.write_text(text, encoding="utf-8")

    print(f"Compared {len(rows)} runs -> {out_dir / 'final_comparison.csv'}")
    for w in winners:
        print(f"  WINNER {w['task']}: {w['model']} ({w['strategy']}, {w['platform']})")
    print(f"Ledger updated: {LEDGER}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
